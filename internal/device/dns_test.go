func TestResolvconfConfig(t *testing.T) {
	if got, want := resolvconfConfig("10.13.13.1", "bntso.internal"), "nameserver 10.13.13.1\nsearch bntso.internal\n"; got != want {
		t.Fatalf("resolvconf config = %q, want %q", got, want)
	}
	if got, want := resolvconfConfig("192.0.2.1", ""), "nameserver 192.0.2.1\n"; got != want {
		t.Fatalf("resolvconf config without search = %q, want %q", got, want)
	}
}

func TestParseFileDNSSearch(t *testing.T) {
	path := filepath.Join(t.TempDir(), "wg0.conf")
	contents := "[Interface]\nDNS = 10.13.13.1\nDNSSearch = bntso.internal\n"
	if err := os.WriteFile(path, []byte(contents), 0o600); err != nil {
		t.Fatal(err)
	}
	cfg, err := ParseFile(path)
	if err != nil {
		t.Fatal(err)
	}
	if cfg.DNS != "10.13.13.1" || cfg.DNSSearch != "bntso.internal" {
		t.Fatalf("parsed DNS = %q, search = %q", cfg.DNS, cfg.DNSSearch)
	}
}

type dnsCommandCall struct {
	name  string
	args  []string
	input string
}

func newTestDNSManager(t *testing.T, resolvConf, nsswitch string) (*dnsManager, *[]dnsCommandCall) {
	t.Helper()
	dir := t.TempDir()
	resolvConfPath := filepath.Join(dir, "resolv.conf")
	if err := os.WriteFile(resolvConfPath, []byte(resolvConf), 0o644); err != nil {
		t.Fatal(err)
	}
	nsswitchPath := filepath.Join(dir, "nsswitch.conf")
	if err := os.WriteFile(nsswitchPath, []byte(nsswitch), 0o644); err != nil {
		t.Fatal(err)
	}
	calls := new([]dnsCommandCall)
	m := &dnsManager{
		resolvConfPath: resolvConfPath,
		backupPath:     filepath.Join(dir, "resolv.conf.backup"),
		nsswitchPath:   nsswitchPath,
		lookPath: func(name string) (string, error) {
			return "/usr/bin/" + name, nil
		},
	}
	m.runCommand = func(name string, args []string, input string) ([]byte, error) {
		*calls = append(*calls, dnsCommandCall{name: name, args: slices.Clone(args), input: input})
		if slices.Equal(args, []string{"status"}) {
			return nil, errors.New("systemd-resolved inactive")
		}
		return nil, nil
	}
	return m, calls
}

func TestDNSManagerResolved(t *testing.T) {
	tests := map[string]struct {
		resolvConf string
		nsswitch   string
	}{
		"stub resolver": {
			resolvConf: "# Generated by systemd-resolved\nnameserver 127.0.0.53\n",
			nsswitch:   "hosts: files dns\n",
		},
		"nss resolve": {
			resolvConf: "# Generated by NetworkManager\nnameserver 192.0.2.1\n",
			nsswitch:   "hosts: files resolve dns\n",
		},
	}
	for name, test := range tests {
		t.Run(name, func(t *testing.T) {
			m, calls := newTestDNSManager(t, test.resolvConf, test.nsswitch)
			m.runCommand = func(name string, args []string, input string) ([]byte, error) {
				*calls = append(*calls, dnsCommandCall{name: name, args: slices.Clone(args), input: input})
				return nil, nil
			}
			if note, err := m.apply("wg0", "fd7a::1", "bntso.internal"); err != nil || note != "" {
				t.Fatalf("apply resolved DNS: note = %q, err = %v", note, err)
			}
			want := []dnsCommandCall{
				{name: "/usr/bin/resolvectl", args: []string{"status"}},
				{name: "/usr/bin/resolvectl", args: []string{"dns", "wg0", "fd7a::1"}},
				{name: "/usr/bin/resolvectl", args: []string{"domain", "wg0", "bntso.internal"}},
				{name: "/usr/bin/resolvectl", args: []string{"default-route", "wg0", "true"}},
			}
			if !slices.EqualFunc(*calls, want, func(a, b dnsCommandCall) bool {
				return a.name == b.name && a.input == b.input && slices.Equal(a.args, b.args)
			}) {
				t.Fatalf("commands = %#v, want %#v", *calls, want)
			}
		})
	}
}

func TestDNSManagerResolvconf(t *testing.T) {
	m, calls := newTestDNSManager(t, "# Generated by resolvconf\nnameserver 192.0.2.1\n", "hosts: files dns\n")
	if note, err := m.apply("wg0", "fd7a::1", "bntso.internal"); err != nil || note != "" {
		t.Fatalf("apply resolvconf DNS: note = %q, err = %v", note, err)
	}
	want := []dnsCommandCall{
		{name: "/usr/bin/resolvectl", args: []string{"status"}},
		{name: "/usr/bin/resolvconf", args: []string{"-a", "wg0", "-m", "0", "-x"}, input: "nameserver fd7a::1\nsearch bntso.internal\n"},
	}
	if !slices.EqualFunc(*calls, want, func(a, b dnsCommandCall) bool {
		return a.name == b.name && a.input == b.input && slices.Equal(a.args, b.args)
	}) {
		t.Fatalf("apply commands = %#v, want %#v", *calls, want)
	}
	*calls = nil
	if note, err := m.remove("wg0"); err != nil || note != "" {
		t.Fatalf("remove resolvconf DNS: note = %q, err = %v", note, err)
	}
	want = []dnsCommandCall{
		{name: "/usr/bin/resolvectl", args: []string{"status"}},
		{name: "/usr/bin/resolvconf", args: []string{"-d", "wg0"}},
	}
	if !slices.EqualFunc(*calls, want, func(a, b dnsCommandCall) bool {
		return a.name == b.name && a.input == b.input && slices.Equal(a.args, b.args)
	}) {
		t.Fatalf("remove commands = %#v, want %#v", *calls, want)
	}
}

func TestDNSManagerDirectRoundTrip(t *testing.T) {
	original := "# Generated by NetworkManager\nsearch example.net\nnameserver 192.0.2.1\n"
	m, calls := newTestDNSManager(t, original, "hosts: files dns\n")
	m.runCommand = func(name string, args []string, input string) ([]byte, error) {
		*calls = append(*calls, dnsCommandCall{name: name, args: slices.Clone(args), input: input})
		return nil, nil
	}
	note, err := m.apply("wg0", "fd7a::1", "bntso.internal")
	if err != nil {
		t.Fatal(err)
	}
	if !strings.Contains(note, "managing") {
		t.Fatalf("direct apply note = %q", note)
	}
	if got := len(*calls); got != 1 {
		t.Fatalf("direct apply ran %d commands, want only resolved detection", got)
	}
	backup, err := os.ReadFile(m.backupPath)
	if err != nil {
		t.Fatal(err)
	}
	if string(backup) != original {
		t.Fatalf("backup = %q, want %q", backup, original)
	}
	managed, err := os.ReadFile(m.resolvConfPath)
	if err != nil {
		t.Fatal(err)
	}
	wantManaged := directDNSMarker + "\nnameserver fd7a::1\nsearch bntso.internal\n"
	if string(managed) != wantManaged {
		t.Fatalf("managed resolv.conf = %q, want %q", managed, wantManaged)
	}
	if note, err := m.remove("wg0"); err != nil || !strings.Contains(note, "restored") {
		t.Fatalf("restore direct DNS: note = %q, err = %v", note, err)
	}
	restored, err := os.ReadFile(m.resolvConfPath)
	if err != nil {
		t.Fatal(err)
	}
	if string(restored) != original {
		t.Fatalf("restored resolv.conf = %q, want %q", restored, original)
	}
	if _, err := os.Stat(m.backupPath); !errors.Is(err, os.ErrNotExist) {
		t.Fatalf("backup still exists after restore: %v", err)
	}
}

func TestDNSManagerDirectPreservesExternalChanges(t *testing.T) {
	m, _ := newTestDNSManager(t, "# Generated by NetworkManager\nnameserver 192.0.2.1\n", "hosts: files dns\n")
	if _, err := m.apply("wg0", "fd7a::1", "bntso.internal"); err != nil {
		t.Fatal(err)
	}
	external := "# Generated by NetworkManager\nnameserver 198.51.100.1\n"
	if err := os.WriteFile(m.resolvConfPath, []byte(external), 0o644); err != nil {
		t.Fatal(err)
	}
	note, err := m.remove("wg0")
	if err != nil {
		t.Fatal(err)
	}
	if !strings.Contains(note, "changed externally") {
		t.Fatalf("external change note = %q", note)
	}
	contents, err := os.ReadFile(m.resolvConfPath)
	if err != nil {
		t.Fatal(err)
	}
	if string(contents) != external {
		t.Fatalf("external resolv.conf was overwritten: %q", contents)
	}
	if _, err := os.Stat(m.backupPath); err != nil {
		t.Fatalf("backup was not retained: %v", err)
	}
}

func TestDNSManagerDirectPreservesSymlink(t *testing.T) {
	m, _ := newTestDNSManager(t, "nameserver 192.0.2.1\n", "hosts: files dns\n")
	target := m.resolvConfPath
	link := filepath.Join(filepath.Dir(target), "resolv-link.conf")
	if err := os.Symlink(target, link); err != nil {
		t.Fatal(err)
	}
	m.resolvConfPath = link
	if _, err := m.apply("wg0", "fd7a::1", "bntso.internal"); err != nil {
		t.Fatal(err)
	}
	info, err := os.Lstat(link)
	if err != nil {
		t.Fatal(err)
	}
	if info.Mode()&os.ModeSymlink == 0 {
		t.Fatal("resolv.conf symlink was replaced")
	}
	contents, err := os.ReadFile(target)
	if err != nil {
		t.Fatal(err)
	}
	if !directDNSManaged(contents) {
		t.Fatalf("symlink target was not updated: %q", contents)
	}
}
