package device

import (
	"errors"
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"strings"
)

const (
	defaultResolvConfPath       = "/etc/resolv.conf"
	defaultResolvConfBackupPath = "/etc/resolv.conf.bntsovpn-backup"
	defaultNSSwitchPath         = "/etc/nsswitch.conf"
	directDNSMarker             = "# Generated by bntsovpn"
)

type dnsManager struct {
	resolvConfPath string
	backupPath     string
	nsswitchPath   string
	lookPath       func(string) (string, error)
	runCommand     func(string, []string, string) ([]byte, error)
}

var systemDNSManager = dnsManager{
	resolvConfPath: defaultResolvConfPath,
	backupPath:     defaultResolvConfBackupPath,
	nsswitchPath:   defaultNSSwitchPath,
	lookPath:       exec.LookPath,
	runCommand: func(name string, args []string, input string) ([]byte, error) {
		cmd := exec.Command(name, args...)
		cmd.Stdin = strings.NewReader(input)
		return cmd.CombinedOutput()
	},
}

type dnsBackend int

const (
	dnsBackendDirect dnsBackend = iota
	dnsBackendResolved
	dnsBackendResolvconf
)

// ApplyDNS registers the DNS server and optional search domain using the
// active system resolver, resolvconf, or a backed-up resolv.conf as a last resort.
func ApplyDNS(iface, dns, search string) (string, error) {
	if dns == "" {
		return "", nil
	}
	return systemDNSManager.apply(iface, dns, search)
}

// RemoveDNS unregisters DNS using the currently detected backend. Directly
// managed resolv.conf contents are restored only if they have not changed externally.
func RemoveDNS(iface, dns string) (string, error) {
	if dns == "" {
		return "", nil
	}
	return systemDNSManager.remove(iface)
}

func (m *dnsManager) apply(iface, dns, search string) (string, error) {
	switch m.detectBackend() {
	case dnsBackendResolved:
		return "", m.applyResolved(iface, dns, search)
	case dnsBackendResolvconf:
		return "", m.applyResolvconf(iface, dns, search)
	default:
		return m.applyDirect(dns, search)
	}
}

func (m *dnsManager) remove(iface string) (string, error) {
	switch m.detectBackend() {
	case dnsBackendResolved:
		bin, _ := m.lookPath("resolvectl")
		if out, err := m.runCommand(bin, []string{"revert", iface}, ""); err != nil {
			return "", fmt.Errorf("resolvectl revert %s: %v (%s)", iface, err, strings.TrimSpace(string(out)))
		}
		return "", nil
	case dnsBackendResolvconf:
		bin, _ := m.lookPath("resolvconf")
		if out, err := m.runCommand(bin, []string{"-d", iface}, ""); err != nil {
			return "", fmt.Errorf("resolvconf -d %s: %v (%s)", iface, err, strings.TrimSpace(string(out)))
		}
		return "", nil
	default:
		note, _, err := m.removeDirect()
		return note, err
	}
}

func (m *dnsManager) detectBackend() dnsBackend {
	if m.resolvedActive() && m.resolvedIsSystemResolver() {
		return dnsBackendResolved
	}
	contents, err := os.ReadFile(m.resolvConfPath)
	if err == nil && resolvConfOwner(contents) == "resolvconf" {
		if _, err := m.lookPath("resolvconf"); err == nil {
			return dnsBackendResolvconf
		}
	}
	return dnsBackendDirect
}

func (m *dnsManager) resolvedActive() bool {
	bin, err := m.lookPath("resolvectl")
	if err != nil {
		return false
	}
	_, err = m.runCommand(bin, []string{"status"}, "")
	return err == nil
}

func (m *dnsManager) resolvedIsSystemResolver() bool {
	if m.nsswitchUsesResolved() {
		return true
	}
	contents, err := os.ReadFile(m.resolvConfPath)
	if err != nil {
		return false
	}
	servers := resolvConfNameservers(contents)
	if len(servers) == 0 {
		return false
	}
	for _, server := range servers {
		if server != "127.0.0.53" {
			return false
		}
	}
	return true
}

func (m *dnsManager) nsswitchUsesResolved() bool {
	contents, err := os.ReadFile(m.nsswitchPath)
	if err != nil {
		return false
	}
	for line := range strings.SplitSeq(string(contents), "\n") {
		fields := strings.Fields(line)
		if len(fields) < 2 || fields[0] != "hosts:" {
			continue
		}
		for _, field := range fields[1:] {
			if strings.HasPrefix(field, "#") {
				break
			}
			switch field {
			case "dns":
				return false
			case "resolve":
				return true
			}
		}
	}
	return false
}

func resolvConfOwner(contents []byte) string {
	for line := range strings.SplitSeq(string(contents), "\n") {
		line = strings.TrimSpace(line)
		if !strings.HasPrefix(line, "#") {
			continue
		}
		switch {
		case strings.Contains(line, directDNSMarker):
			return "bntsovpn"
		case strings.Contains(strings.ToLower(line), "systemd-resolved"):
			return "systemd-resolved"
		case strings.Contains(strings.ToLower(line), "networkmanager"):
			return "NetworkManager"
		case strings.Contains(strings.ToLower(line), "resolvconf"):
			return "resolvconf"
		}
	}
	return ""
}

func resolvConfNameservers(contents []byte) []string {
	var servers []string
	for line := range strings.SplitSeq(string(contents), "\n") {
		fields := strings.Fields(line)
		if len(fields) >= 2 && fields[0] == "nameserver" {
			servers = append(servers, fields[1])
		}
	}
	return servers
}

func (m *dnsManager) applyResolved(iface, dns, search string) error {
	bin, _ := m.lookPath("resolvectl")
	commands := [][]string{
		{"dns", iface, dns},
		{"domain", iface, search},
		{"default-route", iface, "true"},
	}
	for _, args := range commands {
		if out, err := m.runCommand(bin, args, ""); err != nil {
			return fmt.Errorf("resolvectl %s %s: %v (%s)", args[0], iface, err, strings.TrimSpace(string(out)))
		}
	}
	return nil
}

func (m *dnsManager) applyResolvconf(iface, dns, search string) error {
	bin, _ := m.lookPath("resolvconf")
	input := resolvconfConfig(dns, search)
	if out, err := m.runCommand(bin, []string{"-a", iface, "-m", "0", "-x"}, input); err != nil {
		return fmt.Errorf("resolvconf -a %s: %v (%s)", iface, err, strings.TrimSpace(string(out)))
	}
	return nil
}

func resolvconfConfig(dns, search string) string {
	config := "nameserver " + dns + "\n"
	if search != "" {
		config += "search " + search + "\n"
	}
	return config
}

func (m *dnsManager) applyDirect(dns, search string) (string, error) {
	contents, mode, err := readDNSFile(m.resolvConfPath)
	if err != nil {
		return "", fmt.Errorf("read %s: %w", m.resolvConfPath, err)
	}
	if !directDNSManaged(contents) {
		if err := atomicWriteDNSFile(m.backupPath, contents, mode); err != nil {
			return "", fmt.Errorf("back up %s to %s: %w", m.resolvConfPath, m.backupPath, err)
		}
	}
	managed := directDNSMarker + "\n" + resolvconfConfig(dns, search)
	if err := atomicWriteDNSFile(m.resolvConfPath, []byte(managed), mode); err != nil {
		return "", fmt.Errorf("write %s: %w", m.resolvConfPath, err)
	}
	return fmt.Sprintf("no active systemd-resolved or resolvconf configuration detected — managing %s directly", m.resolvConfPath), nil
}

func (m *dnsManager) removeDirect() (string, bool, error) {
	contents, mode, readErr := readDNSFile(m.resolvConfPath)
	if readErr != nil {
		return "", true, fmt.Errorf("read %s: %w", m.resolvConfPath, readErr)
	}
	backup, backupErr := os.ReadFile(m.backupPath)
	if backupErr != nil && !errors.Is(backupErr, os.ErrNotExist) {
		return "", true, fmt.Errorf("read DNS backup %s: %w", m.backupPath, backupErr)
	}
	managed := directDNSManaged(contents)
	if !managed && errors.Is(backupErr, os.ErrNotExist) {
		return "", false, nil
	}
	if !managed {
		return fmt.Sprintf("%s changed externally — left it unchanged and retained DNS backup %s", m.resolvConfPath, m.backupPath), true, nil
	}
	if errors.Is(backupErr, os.ErrNotExist) {
		return fmt.Sprintf("could not restore %s — DNS backup %s is missing", m.resolvConfPath, m.backupPath), true, nil
	}
	if err := atomicWriteDNSFile(m.resolvConfPath, backup, mode); err != nil {
		return "", true, fmt.Errorf("restore %s: %w", m.resolvConfPath, err)
	}
	if err := os.Remove(m.backupPath); err != nil {
		return "", true, fmt.Errorf("remove DNS backup %s: %w", m.backupPath, err)
	}
	return fmt.Sprintf("restored %s from %s", m.resolvConfPath, m.backupPath), true, nil
}

func directDNSManaged(contents []byte) bool {
	for line := range strings.SplitSeq(string(contents), "\n") {
		if strings.TrimSpace(line) == directDNSMarker {
			return true
		}
	}
	return false
}

func readDNSFile(path string) ([]byte, os.FileMode, error) {
	info, err := os.Stat(path)
	if errors.Is(err, os.ErrNotExist) {
		return nil, 0o644, nil
	}
	if err != nil {
		return nil, 0, err
	}
	contents, err := os.ReadFile(path)
	if err != nil {
		return nil, 0, err
	}
	return contents, info.Mode().Perm(), nil
}

func atomicWriteDNSFile(path string, contents []byte, mode os.FileMode) error {
	target := path
	if info, err := os.Lstat(path); err == nil && info.Mode()&os.ModeSymlink != 0 {
		target, err = filepath.EvalSymlinks(path)
		if err != nil {
			return err
		}
	}
	file, err := os.CreateTemp(filepath.Dir(target), "."+filepath.Base(target)+".bntsovpn-*")
	if err != nil {
		return err
	}
	tempPath := file.Name()
	defer os.Remove(tempPath)
	if err := file.Chmod(mode); err != nil {
		file.Close()
		return err
	}
	if _, err := file.Write(contents); err != nil {
		file.Close()
		return err
	}
	if err := file.Sync(); err != nil {
		file.Close()
		return err
	}
	if err := file.Close(); err != nil {
		return err
	}
	return os.Rename(tempPath, target)
}
